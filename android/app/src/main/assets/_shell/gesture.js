  // 第九节（A12 · 2026-10-04 晚）：两张全屏（`html.fs-net`）= **两张绑成一个整体**
  // -------------------------------------------------------------------------
  // 佘先生：「两张图片全屏的状态下的我不能正常放大，而且不能移动图片，现在要求两张图片
  //   的状态下把两张图片绑定在一起，缩放和移动等其他的操作**同单张图片的操作一致**」。
  //
  // ★ 真机实测（`tools/_dbg_fsnet.py` v3 —— **必须量照片本身**，见下）：
  //   · 捏合**是**工作的，走书那套 `applyZoom`（**逐张、无边界夹紧**）——
  //     那是桌面 Phase 34 的既定口径："位置只由中心瞄点决定，照片超出屏幕也不管"。
  //     手机上就表现为"两张飞出去、找不到图" ⇒ 他说的"**不正常**"在这里。
  //   · 单指拖动**根本没有这条路** ⇒ 照片一个像素都不动（壳里从来没写过）。
  //   ⚠ 自己踩的坑：v1/v2 探针量 `.book-rig`（整本书的容器）⇒ 它**恒不变**
  //     ⇒ 得出"捏合完全没反应"的**假结论**。书的放大是**逐张照片**写 img 的 transform，
  //     容器当然不动。**判据要钉在真正会变的那个元素上**（铁律 135 的同一课）。
  //
  // ★ 这一节 = 把第八节（灯箱）那套手感**原样搬**到 fs-net：
  //     捏合 ⇒ 连续跟手（锚点 = 当帧两指中点）
  //     单指 ⇒ 平移
  //     **边界夹紧** ⇒ 合起来比视口小就居中、比视口大就不许露背景（与 `lbClampV` 同一套规矩）
  //   唯一的差别：这里的"图"是**当前跨页所有照片合起来的外接矩形**，于是
  //   两张**天然绑在一起** —— 同一个 k、同一个平移量、同一个锚点，不可能各走各的。
  //
  // ★ 刻意**不做**的三件事（都不许"顺手加"）：
  //   · 不加"双击缩放" —— fs-net 下双击照片是**进单张全屏**（第五节），抢了就破功；
  //   · 不动轻点翻页 / 长按 —— 全部原样；
  //   · 不动书的 `applyZoom` —— 复位直接用它自己的 `resetZoomAll()`（书翻页时也调它）。
  //
  // ★★ A12 落地后真机实测又抓出**两个坑**（都只在真手指下现形，合成触摸两条都测不出）：
  //   ① **拖不动（只跟手 1/7）**：`onTouchMove` 里"长按取消：手指挪动了"那一句会调
  //      `cancelLong()`，而它顺手 `unbindMove()` ⇒ 把 touchmove 监听**整条摘掉**
  //      ⇒ 越过 `LONG_SLOP` 之后的 20 个 move 全丢。实测 120px 的手指只兑现 17.4px。
  //      修：`cancelLong()` 里加 `!lbG && !fnG` —— 手势层还在吃这串触摸就不许摘监听。
  //      证据：`tools/_dbg_fsnet_drag.py`（合成两下 move 只兑现第一下 +60）。
  //   ② **一拖就被复位**：翻页库的 `touchstart` 挂在**书自己的元素**上、并在 250ms 后
  //      自行 `startUserTouch()`，`touchend` 挂在 **window** 上 `userStop()` ⇒
  //      **就算一个 move 都没收到，它也能凭"起点→终点"判成滑动翻页** ⇒ 页位 3→5，
  //      书在 `flip` 事件里调 `resetZoomAll()` ⇒ 用户看到"刚放大的图又缩回去了"。
  //      修：接管这一手时在 `onTouchStart` 里 `stopPropagation()`，让库连起点都拿不到。
  //      证据：`tools/_dbg_fsnet_stack.py`（抓到栈 `resetZoomAll ← flipbook.js:455
