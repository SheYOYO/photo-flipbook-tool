  // 佘先生：「手机端的图片放缩 UI **不要参考电脑端，改结构**，参照现有的成熟的图片的
  //   手机软件的 UI」＋「双击图片后单张图片的全屏显示效果不稳定，**容易闪烁后退出**」。
  //
  // ★ 为什么是"改结构"而不是打补丁 —— 灯原来那套是**桌面**的，两条都对不上手机：
  //   · 缩放挂在**滚轮**上（`lightboxZoom(event)`，以**光标**为锚点、一格 1.18 倍、
  //     还带 60ms 冷却）⇒ 手机端只能把捏合**换算成格数**去喂它 ⇒ 一跳一跳、不跟手，
  //     手指一动锚点就跟着换（佘先生上一条说的"以触点为中心"就是这个观感）。
  //   · 平移挂在 **pointer** 上，而 `.lightbox` **没有 `touch-action: none`**
  //     （书只给 `.book / .stf__*` 写了这一条）⇒ 真机把手势判成"滚动"
  //     ⇒ 手指刚动就发 `pointercancel` ⇒ **放大后根本拖不动**（他实测的那条）。
  //     真机取证（`tools/_dbg_zoom.py`）：合成 PointerEvent 拖 ⇒ 图**动了**（书逻辑没问题）；
  //     `adb shell input swipe` 真拖 ⇒ `pointerdown → pointermove ×1 → pointercancel`
  //     ⇒ 图**只挪了 8px**。两条结论不一致 ⇒ 病在浏览器介入这一层，不在书里。
  //
  // ★ 换成成熟看图软件那一套（书一个字不改，全在壳里）：
  //     双指捏合 ⇒ **连续跟手**，锚点 = **两指中点**（行业标准）
  //     单指拖动 ⇒ 平移；**到边界就停**（图比视口小 ⇒ 那个方向自动居中）
  //     双击图片 ⇒ 1x ⇄ 2x（以双击那一点为中心）
  //     点暗处   ⇒ 关掉（书自己的 click handler，不动它）
  //   还要**挡掉书的手势**（不然两套一起动，位置互相打架），并**吃掉那一下补发的 click**：
  //   真机 `touchend` 后约 20ms 会补发兼容鼠标事件（F46），其中 click 的靶子是"当时
  //   DOM 最上层" = 刚打开的 `.lightbox`，而书挂着 `if (target===box) lightboxClose()`
  //   ⇒ **灯箱刚开就被关** = 他说的"闪一下又退出"（机制已在真机坐实：
  //   `tools/_dbg_lbflash.py` 往暗处派一下 click ⇒ `closes=1`、`hidden=true`）。
  // =========================================================================

  /** 灯箱里那张 `<img>` */
  function lbImgEl() {
    try {
      var b = lightboxBoxEl();
      return b ? b.querySelector('.lightbox__img') : null;
    } catch (e) { return null; }
  }

  /** 灯的当前视图 —— **量纲与书逐字一致**：`transform-origin: 0 0` +
   *  `translate(x,y) scale(s)` ⇒ `x/y` 就是"图左上角落在视口的哪个像素"，
   *  `w/h` 是 1 倍时图占多少（书的 `lightboxFit/lightboxApply` 就是这么写的）。
   *  ⚠ 另立一套量纲正是书 findings 91 栽过的那类错位漂移，这里不重犯。
   *  ⚠ 读**内联样式**（书每次都写全量 `translate(...) scale(...)`），不解析 matrix。 */
  function lbView() {
    var img = lbImgEl();
    if (!img) { return null; }
    var w = parseFloat(img.style.width) || 0;
    var h = parseFloat(img.style.height) || 0;
    var m = /translate\(\s*(-?[\d.]+)px,\s*(-?[\d.]+)px\)\s*scale\(\s*([\d.]+)\s*\)/
              .exec(img.style.transform || '');
    if (m && w > 0 && h > 0) {
      return { s: parseFloat(m[3]), x: parseFloat(m[1]), y: parseFloat(m[2]), w: w, h: h };
    }
    var r = img.getBoundingClientRect();          // 兜底：书还没写过样式时按几何实测
    /* ⚠ 修（2026-10-04）：原写法这里重复判了一次 `!r.width`（第二个应为 `!r.height`），
       而且兜底一律当 1 倍 —— 万一书的 transform 已 scale 过、width/height 却没写内联样式，
       就会把"缩放后的几何"当成 1 倍尺寸 ⇒ 后面的夹取 / 缩放锚点全跟着错。
       这里按 transform 里解析到的 `s` 折回去（`getBoundingClientRect` 量的是缩放后的大小）。 */
    if (!r.width || !r.height) { return null; }
    var s0 = m ? parseFloat(m[3]) : 1;
    if (!(s0 > 0)) { s0 = 1; }
    return { s: s0,
             x: m ? parseFloat(m[1]) : r.left,
             y: m ? parseFloat(m[2]) : r.top,
             w: r.width / s0, h: r.height / s0 };
  }

  /** **唯一出口**：落位。
   *  ⚠ 顺手把书的 `lightboxState` 一起写：它是顶层的 `let` —— **不挂 window**，
   *    但壳与书共用同一个全局词法环境 ⇒ 这里能直接引用（`typeof` 探一下，
   *    老成品没有它就退化成"只写 DOM"，不会报错）。不同步的话，书的
   *    resize / `lightboxFit()` 会拿旧值把我们拽回去。 */
  function lbPaint(v) {
    var img = lbImgEl();
    if (!img) { return; }
    img.style.transform = 'translate(' + v.x + 'px,' + v.y + 'px) scale(' + v.s + ')';
    try {
      if (typeof lightboxState !== 'undefined' && lightboxState) {
        lightboxState.s = v.s;
        lightboxState.x = v.x;
        lightboxState.y = v.y;
      }
    } catch (e) { /* 拿不到就不写 */ }
  }

  /** 倍率上限：优先用书的 `LIGHTBOX_MAX`（它是 `const`，**不挂 window**，
   *  所以只能用 `typeof` 在全局词法环境里探），探不到才用壳里写死的那个。 */
  function lbMax() {
    try {
      if (typeof LIGHTBOX_MAX === 'number' && LIGHTBOX_MAX > 1) { return LIGHTBOX_MAX; }
    } catch (e) { /* 忽略 */ }
    return LB_MAX_DEF;
  }

  /** 边界（成熟看图软件的统一规矩）：
   *  · 图**比视口小**的那个方向 ⇒ 居中（拖不动，也不许露缝）
   *  · 图**比视口大** ⇒ 不许拖到露出背景（`x ∈ [vw−wS, 0]`） */
  function lbClampV(v) {
    var vw = window.innerWidth, vh = window.innerHeight;
    var wS = v.w * v.s, hS = v.h * v.s;
    v.x = (wS <= vw) ? (vw - wS) / 2 : Math.min(0, Math.max(vw - wS, v.x));
    v.y = (hS <= vh) ? (vh - hS) / 2 : Math.min(0, Math.max(vh - hS, v.y));
    return v;
  }

  /** 围绕视口点 (ax,ay) 把倍率变成 s（那一点底下的"图上位置"在屏幕上保持不动） */
  function lbScaleAround(v0, s, ax, ay) {
    var s2 = Math.min(Math.max(s, LB_MIN), lbMax());
    var ux = (ax - v0.x) / v0.s, uy = (ay - v0.y) / v0.s;   // 锚点在**图上**的位置
    return lbClampV({ s: s2, x: ax - s2 * ux, y: ay - s2 * uy, w: v0.w, h: v0.h });
  }

  // ---- 灯箱手势的运行时状态 ----
  var lbG = null;          // null | {mode:'pan', px,py, v0, moved} | {mode:'pinch', d0, v0}
  var lbOpenedAt = 0;      // 灯箱"刚打开"的时刻（吃补发 click 用）
  var lbMovedAt = 0;       // 灯箱里"刚拖/缩过"的时刻（同一个用）

  function lbActive() { return lightboxOpenNow() && !!lbView(); }
  function lbJustMoved() { return !!lbMovedAt && (Date.now() - lbMovedAt) < 250; }

  /** 手势开始（`onTouchStart` 调）。返回 true = 这一下归灯箱 */
  function lbStart(touches) {
    if (!lbActive()) { return false; }
    var v0 = lbView();
    if (!v0) { return false; }
    bindMove();                                  // 灯箱里需要 touchmove（要 preventDefault）
    if (touches.length >= 2) {
      var d0 = distOf(touches[0], touches[1]);
      lbG = (d0 > PINCH_MIN_D) ? { mode: 'pinch', d0: d0, v0: v0 } : null;
      if (!lbG) { lbG = { mode: 'idle', v0: v0 }; }   // 两指贴太近：先占位，别放行给书
      return true;
    }
    lbG = { mode: 'pan', px: touches[0].clientX, py: touches[0].clientY, v0: v0, moved: false };
    return true;
  }

  /** 手势进行（`onTouchMove` 调）。返回 true = 这一下归灯箱 */
  function lbMove(touches) {
    if (!lbG) { return false; }
    var v0 = lbG.v0;
    if (lbG.mode === 'pinch') {
      if (!touches || touches.length < 2) { return true; }
      var d = distOf(touches[0], touches[1]);
      if (!(d > 1)) { return true; }
      var m = midOf(touches[0], touches[1]);
      /* ★ 连续 + 跟手：倍率按"两指距离之比"直接给（**不再换算成滚轮格数**），
         锚点用**当帧两指中点** ⇒ 中点一挪图也跟着挪，这就是成熟看图软件的手感。 */
      lbPaint(lbScaleAround(v0, v0.s * (d / lbG.d0), m.x, m.y));
      lbMovedAt = Date.now();
      return true;
    }
    if (lbG.mode === 'idle') { return true; }
    // 单指平移
    var t = touches[0];
    var dx = t.clientX - lbG.px, dy = t.clientY - lbG.py;
    if (!lbG.moved && (Math.abs(dx) + Math.abs(dy) < 4)) { return true; }   // 还没算拖动
    lbG.moved = true;
    lbPaint(lbClampV({ s: v0.s, x: v0.x + dx, y: v0.y + dy, w: v0.w, h: v0.h }));
    lbMovedAt = Date.now();
    return true;
  }

  /** 手势收尾（`onTouchEnd` / `onTouchCancel` 调）。返回这一下"动过没有" */
  function lbEnd(touchesLeft) {
    var was = lbG;
    if (!was) { return false; }
    var moved = (was.mode === 'pinch') || !!was.moved;
    if (touchesLeft && touchesLeft.length >= 2) { return moved; }
    if (touchesLeft && touchesLeft.length === 1) {
      // 松到只剩一指 ⇒ 用它当新的平移起点（成熟看图软件就是这个手感）
      var v1 = lbView();
      if (v1) {
        lbG = { mode: 'pan', px: touchesLeft[0].clientX, py: touchesLeft[0].clientY,
                v0: v1, moved: true };
        return true;
      }
    }
    lbG = null;
    /* 收尾：**捏合**缩到 1 倍以内 ⇒ 回正到 1 倍并居中。
       ⚠ 条件必须带 `was.mode === 'pinch'` —— 单指拖动**不做**这个：
         书里那种"图比视口宽"的照片在 1 倍下是**允许左右拖**的，回正会把刚拖到的
         位置一下弹回最左（自测时抓到过：rect 从 -240 被弹回 0）。 */
    var vv = lbView();
    if (vv && was.mode === 'pinch' && vv.s < LB_SNAP_BACK) {
      lbPaint(lbClampV({ s: 1, x: 0, y: 0, w: vv.w, h: vv.h }));
      lbMovedAt = 0;                       // 回正不算"拖过"，别把用户下一手正常 click 吃掉
    }
    return moved;
  }

  /** 灯箱里双击：落在**图片矩形内** ⇒ 1x ⇄ 2x（以双击点为中心）；落在图外 ⇒ 不管
   *  （放行给书那一下 click 去关灯箱 —— 保持既有语义「点暗处关闭」）。 */
  function lbDoubleTap(x, y) {
    var img = lbImgEl();
    if (!img) { return false; }
    var r = img.getBoundingClientRect();
    if (!(x >= r.left && x <= r.right && y >= r.top && y <= r.bottom)) { return false; }
    var v = lbView();
    if (!v) { return false; }
    var target = (v.s < 1.6) ? 2 : 1;      // 相册习惯：在原尺寸与 2 倍之间来回切
    lbPaint(lbScaleAround(v, target, x, y));
    noteDbl({ t: 'lb-zoom', s: target, x: Math.round(x), y: Math.round(y) });
    log('灯箱里双击 ⇒ ' + target + ' 倍');
    return true;
  }

  /** 装上灯箱那一层守卫（`start()` 里调一次）：
   *  ① **挡掉书挂在 `.lightbox` 上的 pointer 手势** —— 灯箱里由壳全权接管；
   *     ⚠ **不 preventDefault**：书里那条血泪注释说得对（取消 pointerdown 会把
   *       随后的 click 一起吞掉），而"点暗处关闭"正靠那个 click。
   *  ② **吃掉"刚打开 / 刚拖过"之后落在灯箱上的 click** —— 见文件头第八节那一段。
   *     ⚠ 只吃这一小段窗（`LB_OPEN_GUARD_MS`）；过了窗，用户主动点暗处关闭照旧有效。
   *  ③ ★ A11：窗内**只吃"落在灯箱底 / 图片上"的那一下**；落在**能按的东西**
   *     （`button` / `a` / `[role=button]` —— 灯箱里就那颗关闭钮）上的，
   *     **过了"刚打开"那一拍一律放行** —— 那才是用户真正想按的东西。
   *     ⚠ 不带这句的话，「点关闭钮退出」会在那 450ms 里被吃掉，症状正是
   *       "点一次不退出"（真机复现：309ms 点 ⇒ 没关；1018ms 点 ⇒ 关）。 */
  function lbInstall() {
    try {
      var swallow = function (e) {
        try { e.stopImmediatePropagation(); } catch (e2) { /* 忽略 */ }
      };
      var types = ['pointerdown', 'pointermove', 'pointerup', 'pointercancel'];
      for (var i = 0; i < types.length; i++) {
        (function (ty) {
          document.addEventListener(ty, function (e) {
            try {
              var b = lightboxBoxEl();
              if (!b || b.hidden) { return; }
              if (!e.target || !b.contains(e.target)) { return; }
              swallow(e);                     // 灯箱里一律不给书处理（书那套是桌面的）
            } catch (e2) { /* 忽略 */ }
          }, true);
        })(types[i]);
      }
      document.addEventListener('click', function (e) {
        try {
          var b = lightboxBoxEl();
          if (!b || b.hidden) { return; }
          var t = e.target;
          if (!t || !b.contains(t)) { return; }
          var now = Date.now();
          var justOpen = (now - lbOpenedAt) < LB_OPEN_GUARD_MS;
          var justMove = (now - lbMovedAt) < LB_OPEN_GUARD_MS;
          /* ★★ A11（2026-10-04）：落在**能按的东西**上（灯箱里那颗关闭钮）⇒
             过了"刚打开"那一拍就一律**放行** —— 用户点关闭钮是**明确意图**，
             不该被这道守卫吃掉。
             真机复现（`tools/_dbg_close.py`，走壳的真实入口打开灯箱）：
               打开后 **309ms** 点关闭钮 ⇒ click 被吃 ⇒ 灯箱**还开着**（"点一次不退出"）；
               1018ms 再点 ⇒ 正常关掉。⇒ 全是这道 450ms 窗吃的。
             ⚠ 为什么还要 `!justOpen`：双击打开灯箱时那记**补发的 click** 有可能正好
               落在关闭钮的矩形内（照片是宽幅、一直铺到右上角时就会）—— 那一拍必须
               继续吃，否则"闪一下又退出"会从后门回来（A10 的护城河不能破）。 */
          var onCtl = false;
          try {
            onCtl = !!(t.nodeType === 1 && typeof t.closest === 'function' &&
                       t.closest('button, a, [role="button"]'));
          } catch (e3) { onCtl = false; }
          if (onCtl && !justOpen) { return; }
          if (justOpen || justMove) {
            swallow(e);
            try { e.preventDefault(); } catch (e2) { /* 忽略 */ }
            log('吃掉灯箱上那一下补发的 click（刚打开 / 刚拖过）');
          }
        } catch (e2) { /* 忽略 */ }
      }, true);
      log('灯箱手势层已装上（手机看图式：捏合 / 拖动 / 双击 + 吃补发 click）');
    } catch (e) { log('灯箱手势层装上失败：' + e); }
  }

