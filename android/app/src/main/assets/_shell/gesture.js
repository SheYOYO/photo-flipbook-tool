  function shellFlipMs() {
    try {
      var v = Number(window.__shellFlipMs);
      /* 只接受**有限正数**：speed.js 存的是库参数尺度（≥1）。
         非法就回默认值，绝不把 NaN 写进 flippingTime（库会抛 Invalid flipping time）。 */
      if (isFinite(v) && v > 0) { return v; }
    } catch (e) { /* 忽略 */ }
    return FLIP_MS;
  }
