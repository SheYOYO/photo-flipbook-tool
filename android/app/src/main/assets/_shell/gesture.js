  /** 撤销"被扣住的第一下"。`why` 只用于诊断（`double` / `pinch` / `pinch-end` / …） */
  function cancelPending(why) {
    if (timer) { clearTimeout(timer); timer = null; }
    if (pending) {
      noteSingle({ t: 'canceled', why: why, dt: pending.dt });
      pending = null;
    }
  }

  /**
   * 把这一下**扣住** —— 挂起 `SINGLE_DELAY_MS`，窗内没人来就兑现成一次翻页。
   *
   * 为什么不立刻翻：那正是"双击结果不稳定"的根（F69）。第一下翻走了，第二下就只能
   * 看到一个已经翻过页的书 ⇒ "闪一下 / 假翻页 / 有时是翻页"三种现象全从这儿来。
   */
  function holdFirst(x, y, sx, sy, dt) {
    cancelPending('rehold');
    pending = { x: x, y: y, sx: sx, sy: sy, dt: dt };
    timer = setTimeout(function () {
      timer = null;
      var p = pending;
      pending = null;                     // ★ 先摘下来再兑现：兑现过程中来的事件不该被当成"还扣着"
      if (p) { commitSingle(p); }
    }, SINGLE_DELAY_MS);
    noteSingle({ t: 'hold', dt: dt });
  }

  /**
   * 兑现：把扣住的那一下补成一次翻页 —— **走库自己的两条调用**，不自己算翻到哪一页。
   *
   * ⚠ 这时书那条"自己翻"的路已经被 `onMouseDown` 掐掉了（待定窗口内拦 mousedown）
   *   ⇒ 翻页**只由这里发生一次**，不会翻两页。
   */
  function commitSingle(p) {
    var api = flipApi();
    if (!api) { noteSingle({ t: 'fail', why: 'no-api' }); return; }
    try {
      api.startUserTouch(toLocal(p.sx, p.sy));
      api.userStop(toLocal(p.x, p.y));
      noteSingle({ t: 'flip', dt: p.dt, sawMouse: sawMouse });
      log('补翻一次 @' + Math.round(p.x) + ',' + Math.round(p.y) + ' dt=' + p.dt);
    } catch (err) {
      noteSingle({ t: 'fail', why: 'throw', msg: String(err) });
      log('补翻失败：' + err);
    }
  }

